/** The texture key of a word picture, made on first use. Unknown pictures are a blank card, never a crash. */
export function wordTexture(scene: Phaser.Scene, picture: string): string {
  const art = WORD_ART[picture] ?? WORD_ART.star!;
  return makePixelTexture(scene, `word-${picture in WORD_ART ? picture : 'star'}`, art, (ch) => COLORS[ch] ?? null);
}
