export type FriendId = keyof typeof FRIEND_ART;
export const FRIEND_IDS = Object.keys(FRIEND_ART) as FriendId[];

/** Colour for a grid letter, or null for clear. */
export function friendColor(art: FriendArt, ch: string): string | null {
  if (ch === 'o') return FRIEND_OUTLINE;
  return art.palette[ch] ?? null;
}

type Grid = string[][];
type EyeDrawer = (grid: Grid, x: number, ink: string) => void;

/** Clears both eyes to the face colour (the pixel on each eye's inner side), then lets `draw` redraw them. */
function redrawEyes(grid: Grid, draw: EyeDrawer): void {
  const { left, right, top } = FRIEND_EYES;
  for (const x of [left, right]) {
    const skin = grid[top + 1]![x === left ? x + 2 : x - 1]!;
    const ink = grid[top + 1]![x]!;
    for (let y = top; y <= top + 2; y++) grid[y]!.splice(x, 2, skin, skin);
    draw(grid, x, ink);
  }
}

const hasMouth = (grid: Grid): boolean => grid[MOUTH.y]![MOUTH.x] === 'o' && grid[MOUTH.y]![MOUTH.x + 1] === 'o';

/** Closed, smiling ^ ^ eyes, and a wider smile when there is a mouth. */
function happy(grid: Grid): void {
  redrawEyes(grid, (g, x, ink) => {
    const y = FRIEND_EYES.top + 1;
    g[y]!.splice(x, 2, ink, ink);
    g[y + 1]![x - 1] = ink;
    g[y + 1]![x + 2] = ink;
  });
  if (!hasMouth(grid)) return;
  const skin = grid[MOUTH.y]![MOUTH.x - 2]!;
  grid[MOUTH.y]!.splice(MOUTH.x - 1, 4, 'o', skin, skin, 'o');
  grid[MOUTH.y + 1]!.splice(MOUTH.x, 2, 'o', 'o');
}

/** Eyes glance up and the mouth becomes a small dot. */
function thinking(grid: Grid): void {
  redrawEyes(grid, (g, x, ink) => {
    for (let y = FRIEND_EYES.top - 1; y <= FRIEND_EYES.top + 1; y++) g[y]!.splice(x, 2, ink, ink);
  });
  if (hasMouth(grid)) grid[MOUTH.y]![MOUTH.x + 1] = grid[MOUTH.y]![MOUTH.x - 1]!;
}

/** Closed eyes: a short line along the bottom of each eye. */
function blink(grid: Grid): void {
  redrawEyes(grid, (g, x, ink) => g[FRIEND_EYES.top + 2]!.splice(x, 2, ink, ink));
}

/** Lifts the left or right foot by moving that half of the feet rows up. */
const step =
  (side: 'left' | 'right') =>
  (grid: Grid): void => {
    const from = side === 'left' ? 0 : FRIEND_W / 2;
    for (let y = FEET_TOP; y < FRIEND_H; y++) {
      const below = grid[y + STEP_LIFT];
      for (let x = from; x < from + FRIEND_W / 2; x++) grid[y]![x] = below?.[x] ?? '.';
    }
  };

/** Standing, happy, thinking, two walking steps and a blink, in sprite-sheet order. */
export function friendFrames(art: FriendArt): string[][] {
  const pose = (change?: (grid: Grid) => void): string[] => {
    const grid = art.rows.map((r) => r.split(''));
    change?.(grid);
    return grid.map((r) => r.join(''));
  };
  return [pose(), pose(happy), pose(thinking), pose(step('left')), pose(step('right')), pose(blink)];
}
